def _range(s: pd.Series) -> str:
    if pd.api.types.is_bool_dtype(s):
        return f"True: {int(s.sum())}"
    if pd.api.types.is_numeric_dtype(s):
        s = s.dropna()
        return f"{s.min():.4g} – {s.max():.4g}" if len(s) else ""
    n = s.nunique()
    return f"{n} distinct" if n > 12 else ", ".join(map(str, sorted(s.dropna().unique())))


def build_markdown(grades: pd.DataFrame, rare: list[str]) -> str:
    docs = dict(COLUMN_DOCS)
    for el in ELEMENTS:
        note = " (rare: also counted in trace_total)" if el in rare else ""
        docs[el] = ("wt%", f"{el} content, weight percent{note}")
    lines = [
        "# Data dictionary: `steels_clean.csv`",
        "",
        f"One row per canonical steel grade. **{len(grades)} rows × {grades.shape[1]} columns.** "
        "Generated by `src/analysis/data_dictionary.py`; ranges are computed from the file.",
        "",
        "| Column | Unit | Type | Non-null | Range / values | Description |",
        "|---|---|---|---|---|---|",
    ]
    for col in grades.columns:
        unit, desc = docs.get(col, ("", ""))
        s = grades[col]
        lines.append(f"| `{col}` | {unit} | {s.dtype} | {int(s.notna().sum())} | {_range(s)} | {desc} |")
    lines += ["", "Companion file `steels_listings.csv` keeps the de-duplicated raw rows "
                  "(raw name, raw TS, `is_imputed_ts`, `name_format`, `canonical_grade`, `grade_id`) for the "
                  "with/without-imputation sensitivity analysis."]
    return "\n".join(lines) + "\n"


def write_data_dictionary(grades: pd.DataFrame, rare: list[str]) -> None:
    DATA_DICTIONARY_MD.write_text(build_markdown(grades, rare), encoding="utf-8")
