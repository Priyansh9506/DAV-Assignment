# Steps
# --------------------------------------------------------------------------------------------
EXPECTED_COLUMNS = [RAW_NAME, RAW_TS, RAW_LIQUIDUS, RAW_CLASS, *ELEMENTS]


def load_raw(path: Path, log: CleaningLog) -> pd.DataFrame:
    df = pd.read_csv(path)
    log.add("load_raw", 0, len(df), f"Read {path.name}: {df.shape[0]} rows x {df.shape[1]} columns",
            n_columns=df.shape[1])
    return df


def validate_schema(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    missing = [c for c in EXPECTED_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"Raw file is missing columns: {missing}")
    numeric = [RAW_TS, RAW_LIQUIDUS, RAW_CLASS, *ELEMENTS]
    non_numeric = [c for c in numeric if not pd.api.types.is_numeric_dtype(df[c])]
    if non_numeric:
        raise ValueError(f"Columns expected numeric: {non_numeric}")
    n_null = int(df[EXPECTED_COLUMNS].isna().sum().sum())
    if n_null:
        raise ValueError(f"Raw file contains {n_null} nulls; the pipeline assumes none")
    negative = [c for c in ELEMENTS if (df[c] < 0).any()]
    if negative:
        raise ValueError(f"Negative wt% in: {negative}")
    log.add("validate_schema", len(df), len(df), "34 expected columns present, all numeric, 0 nulls, no negative wt%",
            n_nulls=n_null, fe_min=df["Fe"].min(), fe_max=df["Fe"].max())
    return df[EXPECTED_COLUMNS].copy()


def drop_exact_duplicates(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = df.drop_duplicates().reset_index(drop=True)
    log.add("drop_exact_duplicates", len(df), len(out), f"Removed {len(df) - len(out)} exact full-row duplicates")
    return out


def flag_imputed_ts(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = df.copy()
    out["is_imputed_ts"] = np.isclose(out[RAW_TS], IMPUTED_TS_VALUE, atol=IMPUTED_TS_TOL)
    n = int(out["is_imputed_ts"].sum())
    classes = out.loc[out["is_imputed_ts"], RAW_CLASS].value_counts().to_dict()
    log.add("flag_imputed_ts", len(df), len(out),
            f"{n} rows ({n / len(out):.1%}) carry TS = {IMPUTED_TS_VALUE} (the raw column mean); flagged, not dropped",
            n_imputed=n, raw_column_mean=float(df[RAW_TS].mean()), original_class_of_imputed=classes)
    return out


def canonical_key(name: str) -> str:
    """Normalise a grade name so that 'EN 1.0420 (GE200) Cast Non-Alloy Steel' and
    'EN-1.0420-GE200-Cast-Non-Alloy-Steel' map to the same key."""
    key = "".join(ch if ch.isalnum() else " " for ch in name.lower())
    return "-".join(key.split())


def add_canonical_grade(df: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = df.copy()
    out["canonical_grade"] = out[RAW_NAME].map(canonical_key)
    out["name_format"] = np.where(out[RAW_NAME].str.contains(r"[ ()]"), "spaced", "hyphenated")
    comp_per_key = out.groupby("canonical_grade")[ELEMENTS].nunique().max(axis=1)
    liq_per_key = out.groupby("canonical_grade")[RAW_LIQUIDUS].nunique()
    if (comp_per_key > 1).any() or (liq_per_key > 1).any():
        bad = comp_per_key[comp_per_key > 1].index.tolist()[:5]
        raise ValueError(f"canonical_grade maps to >1 composition/liquidus, e.g. {bad}")
    sizes = out.groupby("canonical_grade").size()
    measured = out[~out["is_imputed_ts"]]
    ts_conflicts = int((measured.groupby("canonical_grade")[RAW_TS].nunique() > 1).sum())
    pairs = sizes[sizes == 2].index
    both_measured = int((measured.groupby("canonical_grade").size().reindex(pairs) == 2).sum())
    log.add("add_canonical_grade", len(df), len(out),
            f"{out['canonical_grade'].nunique()} canonical grades; {int((sizes == 2).sum())} listed twice "
            f"(spaced + hyphenated name), {int((sizes == 1).sum())} listed once",
            n_canonical=out["canonical_grade"].nunique(), n_listed_twice=int((sizes == 2).sum()),
            n_listed_once=int((sizes == 1).sum()), name_format_counts=out["name_format"].value_counts().to_dict(),
            twin_pairs_both_measured=both_measured, twin_pairs_with_conflicting_measured_ts=ts_conflicts)
    if ts_conflicts:
        raise ValueError(f"{ts_conflicts} canonical grades have conflicting measured TS")
    return out


def collapse_to_grades(listings: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    """One row per canonical grade. TS comes from any measured listing (twins never conflict,
    asserted above); grades whose every listing is imputed get TS = NaN and is_imputed_ts=True."""
    lst = listings.copy()
    lst["_measured_ts"] = lst[RAW_TS].where(~lst["is_imputed_ts"])
    # prefer the spaced name for display (it is the more readable format)
    lst["_fmt_rank"] = (lst["name_format"] != "spaced").astype(int)
    lst = lst.sort_values(["canonical_grade", "_fmt_rank", RAW_NAME])
    g = lst.groupby("canonical_grade", sort=True)
    grades = pd.DataFrame({
        "display_name": g[RAW_NAME].first(),
        "alt_name": g[RAW_NAME].agg(lambda s: s.iloc[1] if len(s) > 1 else ""),
        "n_listings": g.size(),
        "tensile_strength_mpa": g["_measured_ts"].max(),
        "had_imputed_listing": g["is_imputed_ts"].any(),
        "liquidus_c": g[RAW_LIQUIDUS].first().astype(float),
    })
    grades["is_imputed_ts"] = grades["tensile_strength_mpa"].isna()
    grades = grades.join(g[ELEMENTS].first())
    grades = grades.reset_index()
    grades.insert(0, "grade_id", [f"G{i + 1:04d}" for i in range(len(grades))])
    recovered = int((grades["had_imputed_listing"] & ~grades["is_imputed_ts"]).sum())
    still = int(grades["is_imputed_ts"].sum())
    log.add("collapse_to_grades", len(listings), len(grades),
            f"{len(grades)} grades. {recovered} grades had an imputed listing whose twin carries the measured TS; "
            f"{still} grades have no measured TS at all",
            n_grades=len(grades), n_recovered_from_twin=recovered, n_grades_without_measured_ts=still,
            grades_without_measured_ts=grades.loc[grades["is_imputed_ts"], "display_name"].tolist())
    return grades


def audit_processing_variants(listings: pd.DataFrame, grades: pd.DataFrame, log: CleaningLog) -> None:
    """How many identical compositions carry different strengths, and how much of that is imputation."""
    comp_key = pd.util.hash_pandas_object(listings[ELEMENTS].round(6), index=False)
    row_level = int((listings.groupby(comp_key)[RAW_TS].nunique() > 1).sum())
    meas = listings[~listings["is_imputed_ts"]]
    meas_key = comp_key[~listings["is_imputed_ts"].values]
    measured_level = int((meas.groupby(meas_key.values)[RAW_TS].nunique() > 1).sum())
    gk = pd.util.hash_pandas_object(grades[ELEMENTS].round(6), index=False)
    gm = grades.assign(_k=gk.values).dropna(subset=["tensile_strength_mpa"])
    stats = gm.groupby("_k")["tensile_strength_mpa"].agg(["size", "nunique"])
    log.add("audit_processing_variants", len(grades), len(grades),
            f"{row_level} composition groups show >1 TS at listing level, but only {measured_level} once the "
            f"imputed constant is excluded: the rest is the imputed value disagreeing with the measured twin",
            n_compositions=int(comp_key.nunique()), groups_multi_ts_listing_level=row_level,
            groups_multi_ts_measured_only=measured_level,
            grade_level_multi_member_groups=int((stats["size"] > 1).sum()),
            grade_level_groups_with_different_ts=int((stats["nunique"] > 1).sum()))


def recompute_strength_class(grades: pd.DataFrame, listings: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = grades.copy()
    out["strength_class"] = strength_class(out["tensile_strength_mpa"])
    out["strength_class_label"] = out["strength_class"].map(STRENGTH_CLASS_LABELS)
    meas = listings[~listings["is_imputed_ts"]]
    agreement = float((strength_class(meas[RAW_TS]) == meas[RAW_CLASS]).mean())
    if agreement < 1.0:
        raise ValueError(f"Recomputed class disagrees with original on measured rows ({agreement:.3%})")
    counts = out["strength_class"].value_counts(dropna=False).sort_index()
    log.add("recompute_strength_class", len(grades), len(out),
            f"Class rebuilt from measured TS (edges {STRENGTH_CLASS_EDGES} MPa); matches the original Class on "
            f"100% of measured listings. Grade counts 0/1/2 = "
            f"{int(counts.get(0, 0))}/{int(counts.get(1, 0))}/{int(counts.get(2, 0))}, "
            f"{int(out['strength_class'].isna().sum())} without class",
            agreement_on_measured_listings=agreement,
            grade_class_counts={str(k): int(v) for k, v in counts.items()},
            original_listing_class_counts=listings[RAW_CLASS].value_counts().sort_index().to_dict())
    return out


def strength_class(ts: pd.Series) -> pd.Series:
    lo, hi = STRENGTH_CLASS_EDGES
    cls = pd.Series(np.select([ts < lo, ts <= hi], [0, 1], 2), index=ts.index).astype("Int64")
    return cls.mask(ts.isna())


def flag_default_liquidus(grades: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = grades.copy()
    out["liquidus_is_default"] = out["liquidus_c"] == DEFAULT_LIQUIDUS_C
    n = int(out["liquidus_is_default"].sum())
    log.add("flag_default_liquidus", len(grades), len(out),
            f"{n} grades ({n / len(out):.1%}) have liquidus = {DEFAULT_LIQUIDUS_C} °C; kept but flagged as a "
            f"family-typical default (evidence in 01_cleaning)", n_default=n)
    return out


def group_trace_elements(grades: pd.DataFrame, rare: list[str], log: CleaningLog) -> pd.DataFrame:
    out = grades.copy()
    out["trace_total"] = out[rare].sum(axis=1)
    log.add("group_trace_elements", len(grades), len(out),
            f"{len(rare)} elements non-zero in <{RARE_ELEMENT_MIN_ROWS} de-duplicated rows summed into trace_total: "
            f"{', '.join(rare)}", rare_elements=rare, grades_with_trace=int((out["trace_total"] > 0).sum()))
    return out


def add_features(grades: pd.DataFrame, log: CleaningLog) -> pd.DataFrame:
    out = grades.copy()
    fam = F.assign_family(out)
    out["family"] = fam["family"]
    out["family_label"] = out["family"].map(F.FAMILY_LABELS)
    out["family_source"] = fam["family_source"]
    out["naming_source"] = out["display_name"].map(F.naming_source)
    out["product_form"] = [F.product_form(n, f) for n, f in zip(out["display_name"], out["family"])]
    out["condition_in_name"] = out["display_name"].map(F.condition_in_name)
    out = out.join(F.composition_features(out))
    out["composition_group_id"] = F.composition_group_ids(out)
    grp = out.groupby("composition_group_id")
    out["composition_group_size"] = grp["grade_id"].transform("size")
    out["composition_group_n_measured"] = grp["tensile_strength_mpa"].transform("count")
    log.add("add_features", len(grades), len(out),
            f"family ({out['family'].nunique()} families, {int((out['family_source'] == 'composition_rule').sum())} "
            f"by EN 10020 composition rule), naming_source, product_form, CE, Cr+Ni, Schaeffler Cr/Ni eq, "
            f"composition_group_id ({out['composition_group_id'].nunique()} groups)",
            family_counts=out["family"].value_counts().to_dict(),
            naming_source_counts=out["naming_source"].value_counts().to_dict(),
            product_form_counts=out["product_form"].value_counts().to_dict(),
            n_composition_groups=out["composition_group_id"].nunique(),
            comp_sum_min=out["comp_sum"].min(), comp_sum_max=out["comp_sum"].max())
    return out


