"""Reusable, logged cleaning pipeline: raw listings -> one clean row per steel grade.

Run end to end with ``python -m src.analysis.cleaning``. Each step is a plain function that
takes a DataFrame, returns a new one, and appends a `StepRecord` (rows before/after + details)
to a shared `CleaningLog`, so the notebook, the docs and the tests all read the same numbers.
"""
from __future__ import annotations

import json
import logging
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

from . import features as F
from .constants import (
    CLEAN_GRADES_CSV, CLEAN_LISTINGS_CSV, CLEANING_LOG_JSON, CLEANING_LOG_MD, DATA_RAW, PIPELINE_META_JSON,
    DEFAULT_LIQUIDUS_C, ELEMENTS, IMPUTED_TS_TOL, IMPUTED_TS_VALUE, RARE_ELEMENT_MIN_ROWS,
    RAW_CLASS, RAW_LIQUIDUS, RAW_NAME, RAW_TS, STRENGTH_CLASS_EDGES, STRENGTH_CLASS_LABELS,
)

logger = logging.getLogger("steelscope.cleaning")


# --------------------------------------------------------------------------------------------
# Step log
# --------------------------------------------------------------------------------------------
@dataclass
class StepRecord:
    step: str
    rows_before: int
    rows_after: int
    detail: str
    metrics: dict = field(default_factory=dict)

    @property
    def delta(self) -> int:
        return self.rows_after - self.rows_before


@dataclass
class CleaningLog:
    records: list[StepRecord] = field(default_factory=list)

    def add(self, step: str, before: int, after: int, detail: str, **metrics) -> None:
        rec = StepRecord(step, before, after, detail, _jsonable(metrics))
        self.records.append(rec)
        logger.info("%-28s %5d -> %5d (%+d)  %s", step, before, after, rec.delta, detail)

    def get(self, step: str) -> StepRecord:
        return next(r for r in self.records if r.step == step)

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame(
            [{"step": r.step, "rows_before": r.rows_before, "rows_after": r.rows_after,
              "delta": r.delta, "detail": r.detail} for r in self.records]
        )

    def to_markdown(self) -> str:
        lines = ["# Cleaning log", "", "Generated by `python -m src.analysis.cleaning`.", "",
                 "| # | Step | Rows before | Rows after | Δ | Detail |", "|---|---|---|---|---|---|"]
        for i, r in enumerate(self.records, 1):
            lines.append(f"| {i} | `{r.step}` | {r.rows_before} | {r.rows_after} | {r.delta:+d} | {r.detail} |")
        lines += ["", "## Step metrics", ""]
        for r in self.records:
            if r.metrics:
                lines.append(f"**{r.step}**")
                lines.append("")
                for k, v in r.metrics.items():
                    lines.append(f"- `{k}`: {v}")
                lines.append("")
        return "\n".join(lines)

    def to_json(self) -> str:
        return json.dumps([asdict(r) | {"delta": r.delta} for r in self.records], indent=2)


def _jsonable(obj):
    if isinstance(obj, dict):
        return {str(k): _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        return round(float(obj), 4)
    if isinstance(obj, float):
        return round(obj, 4)
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


