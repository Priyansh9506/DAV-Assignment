GRADE_COLUMN_ORDER = [
    "grade_id", "canonical_grade", "display_name", "alt_name", "n_listings",
    "family", "family_label", "family_source", "naming_source", "product_form", "condition_in_name",
    "tensile_strength_mpa", "is_imputed_ts", "had_imputed_listing", "strength_class", "strength_class_label",
    "liquidus_c", "liquidus_is_default",
    *ELEMENTS, "trace_total", "comp_sum", "alloying_total", "carbon_equivalent", "cr_plus_ni", "cr_eq", "ni_eq",
    "is_stainless_comp", "composition_group_id", "composition_group_size", "composition_group_n_measured",
]


@dataclass
class CleaningResult:
    listings: pd.DataFrame
    grades: pd.DataFrame
    rare_elements: list[str]
    log: CleaningLog


def run_cleaning(raw_path: Path = DATA_RAW) -> CleaningResult:
    log = CleaningLog()
    df = load_raw(raw_path, log)
    df = validate_schema(df, log)
    df = drop_exact_duplicates(df, log)
    df = flag_imputed_ts(df, log)
    listings = add_canonical_grade(df, log)
    rare = F.rare_elements(listings, RARE_ELEMENT_MIN_ROWS)
    grades = collapse_to_grades(listings, log)
    audit_processing_variants(listings, grades, log)
    grades = recompute_strength_class(grades, listings, log)
    grades = flag_default_liquidus(grades, log)
    grades = group_trace_elements(grades, rare, log)
    grades = add_features(grades, log)
    grades = grades[GRADE_COLUMN_ORDER]

    listings = listings.rename(columns={RAW_NAME: "raw_name", RAW_TS: "tensile_strength_raw",
                                        RAW_LIQUIDUS: "liquidus_c", RAW_CLASS: "class_original"})
    listings.insert(0, "listing_id", [f"L{i + 1:04d}" for i in range(len(listings))])
    listings = listings.merge(grades[["canonical_grade", "grade_id", "family", "composition_group_id"]],
                              on="canonical_grade", how="left")
    return CleaningResult(listings=listings, grades=grades, rare_elements=rare, log=log)


def save_outputs(result: CleaningResult) -> None:
    from .data_dictionary import write_data_dictionary

    CLEAN_GRADES_CSV.parent.mkdir(parents=True, exist_ok=True)
    CLEANING_LOG_MD.parent.mkdir(parents=True, exist_ok=True)
    result.grades.to_csv(CLEAN_GRADES_CSV, index=False)
    result.listings.to_csv(CLEAN_LISTINGS_CSV, index=False)
    CLEANING_LOG_MD.write_text(result.log.to_markdown(), encoding="utf-8")
    CLEANING_LOG_JSON.write_text(result.log.to_json(), encoding="utf-8")
    write_data_dictionary(result.grades, result.rare_elements)
    meta = {
        "rare_elements": result.rare_elements,
        "imputed_ts_value": IMPUTED_TS_VALUE,
        "default_liquidus_c": DEFAULT_LIQUIDUS_C,
        "n_grades": len(result.grades),
        "n_measured": int(result.grades["tensile_strength_mpa"].notna().sum()),
        "n_listings": len(result.listings),
    }
    PIPELINE_META_JSON.write_text(json.dumps(meta, indent=2), encoding="utf-8")
    logger.info("Saved %s (%d rows) and %s (%d rows)", CLEAN_GRADES_CSV.name, len(result.grades),
                CLEAN_LISTINGS_CSV.name, len(result.listings))


def load_pipeline_meta() -> dict:
    return json.loads(PIPELINE_META_JSON.read_text(encoding="utf-8"))


def load_clean_grades() -> pd.DataFrame:
    df = pd.read_csv(CLEAN_GRADES_CSV, keep_default_na=True, na_values=[""])
    df["alt_name"] = df["alt_name"].fillna("")
    df["strength_class"] = df["strength_class"].astype("Int64")
    return df


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    result = run_cleaning()
    save_outputs(result)


if __name__ == "__main__":
    main()
